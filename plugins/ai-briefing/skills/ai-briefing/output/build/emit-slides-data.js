// Main emitter: read briefing markdown + state → write slides-data.js.
//
// CLI:
//   node emit-slides-data.js                    # auto-detect meeting_n from state
//   node emit-slides-data.js --meeting-n 21     # override meeting number
//   node emit-slides-data.js --briefing path    # override briefing markdown path
//   node emit-slides-data.js --date 2026-05-08  # override meeting date
import fs from "node:fs/promises";
import path from "node:path";
import { parseBriefing } from "./lib/parse-briefing.js";
import { emitSlides } from "./lib/emit-slides.js";
import { ensureProviderLogos } from "./lib/fetch-logos.js";
import { validateDeck } from "./lib/schema.js";
import { brand as DEFAULT_BRAND, theme as DEFAULT_THEME } from "./brand.js";
import { resolveBrand } from "./lib/brand-overlay.js";
import { buildOutDir, configDir, meetingsDir, slidesDataPath, stateRoot } from "./lib/paths.js";

const PROVIDER_LOGOS = {
  anthropic: "assets/logo-anthropic.svg",
  openai: "assets/logo-openai.svg",
  google: "assets/logo-google.svg",
  cursor: "assets/logo-cursor.svg",
  microsoft: "assets/logo-microsoft.svg",
  xai: "assets/logo-x.svg",
  meta: "assets/logo-meta.svg",
  deepseek: null,
  nvidia: "assets/logo-nvidia.svg",
  tesla: "assets/logo-tesla.svg",
  bun: "assets/logo-bun.svg",
  langchain: "assets/logo-langchain.svg",
  vscode: "assets/logo-visualstudiocode.svg",
  huggingface: "assets/logo-huggingface.svg",
};

function parseArgs(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i++) {
    const k = argv[i];
    if (k === "--meeting-n") out.meetingN = parseInt(argv[++i], 10);
    else if (k === "--briefing") out.briefing = argv[++i];
    else if (k === "--date") out.date = argv[++i];
    else if (k === "--out") out.out = argv[++i];
    else if (k === "--no-fetch-logos") out.noFetchLogos = true;
  }
  return out;
}

async function readState() {
  const statePath = path.join(stateRoot(), "context", "seen-items.json");
  try {
    return JSON.parse(await fs.readFile(statePath, "utf-8"));
  } catch {
    return null;
  }
}

/** Find the latest per-profile-runner run with a non-empty briefing-deltas.md.
 *  Returns the deltas markdown string (newest run wins) or null if none. */
async function readLatestBriefingDeltas() {
  const runsDir = path.join(stateRoot(), "context", "runs");
  let entries;
  try {
    entries = await fs.readdir(runsDir, { withFileTypes: true });
  } catch {
    return null;
  }
  const dirs = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
    .reverse();
  for (const name of dirs) {
    const deltasPath = path.join(runsDir, name, "briefing-deltas.md");
    try {
      const text = await fs.readFile(deltasPath, "utf-8");
      if (text.trim().length > 0) {
        return { runId: name, path: deltasPath, text };
      }
    } catch {
      /* not present */
    }
  }
  return null;
}

/** Merge briefing-deltas.md (per-profile runner output) into the briefing markdown
 *  that downstream slide emit consumes. Appended under "## Per-profile runner deltas"
 *  so parseBriefing keeps the existing structure intact. Returns the merged markdown
 *  if a delta was applied, otherwise the original briefing markdown unchanged. */
async function mergeRunnerDeltas(originalMarkdown) {
  const deltas = await readLatestBriefingDeltas();
  if (!deltas) return { merged: originalMarkdown, deltaApplied: null };

  const sentinel = `<!-- runner-deltas:${deltas.runId} -->`;
  if (originalMarkdown.includes(sentinel)) {
    return { merged: originalMarkdown, deltaApplied: { runId: deltas.runId, alreadyMerged: true } };
  }
  const sep = "\n\n---\n\n## Per-profile runner deltas\n\n";
  const merged = `${originalMarkdown.trimEnd()}${sep}${sentinel}\n${deltas.text.trim()}\n`;
  return { merged, deltaApplied: { runId: deltas.runId, alreadyMerged: false } };
}

function formatWindow(openIso, closeIso) {
  const a = new Date(openIso);
  const b = new Date(closeIso);
  const days = Math.round((b - a) / (1000 * 60 * 60 * 24));
  const fmt = (d) => d.toISOString().slice(0, 10);
  return `${fmt(a)} to ${fmt(b)} (~${days} days)`;
}

function asJsLiteral(v, indent = 0) {
  return JSON.stringify(v, null, 2)
    .split("\n")
    .map((line, i) => (i === 0 ? line : " ".repeat(indent) + line))
    .join("\n");
}

/** Render slides-data.js source from emitted data. Pretty-printed, ESM. */
function renderModule({ meta, theme, providerLogos, slides }) {
  return `// Auto-generated by emit-slides-data.js — DO NOT hand-edit.
// Edit the source briefing markdown and re-run \`node emit-slides-data.js\`.
// Brand tokens (theme + meta defaults) live in brand.js; provider logos in emit-slides-data.js.

export const meta = ${asJsLiteral(meta, 0)};

export const theme = ${asJsLiteral(theme, 0)};

export const providerLogos = ${asJsLiteral(providerLogos, 0)};

export const slides = ${asJsLiteral(slides, 0)};
`;
}

async function main() {
  const args = parseArgs(process.argv);

  // Resolve the active profile's brand.js overlay (org, tagline, logos, theme)
  // over the engine's neutral default. Absent overlay → neutral default. Profile
  // logo paths come back absolute so the downstream build scripts embed them.
  const { brand: BRAND, theme: THEME } = await resolveBrand({
    defaultBrand: DEFAULT_BRAND,
    defaultTheme: DEFAULT_THEME,
    configDir: configDir(),
  });

  // Resolve meeting number + window from state (or args)
  const state = await readState();
  let meetingNumber = args.meetingN;
  let windowStr = "";
  const dateStr = args.date || new Date().toISOString().slice(0, 10);

  if (!meetingNumber) {
    if (state?.current_meeting_window?.meeting_n) {
      meetingNumber = state.current_meeting_window.meeting_n;
    } else if (state?.meeting_n) {
      meetingNumber = state.meeting_n;
    } else {
      meetingNumber = 1;
    }
  }

  // Pick briefing path
  const briefingPath = args.briefing
    ? path.resolve(args.briefing)
    : path.join(meetingsDir(), `meeting-${meetingNumber}.md`);

  console.log(`Reading briefing:  ${briefingPath}`);

  // Generated artifacts land under the per-profile state root, which may not
  // exist yet on a fresh install.
  await fs.mkdir(buildOutDir(), { recursive: true });

  // Merge per-profile runner deltas (latest run with non-empty briefing-deltas.md)
  // before parsing, so emitted slides reflect runner output without needing a
  // separate manual merge into meeting-{N}.md.
  const originalMarkdown = await fs.readFile(briefingPath, "utf-8");
  const { merged, deltaApplied } = await mergeRunnerDeltas(originalMarkdown);
  if (deltaApplied) {
    if (deltaApplied.alreadyMerged) {
      console.log(`Runner deltas:     ${deltaApplied.runId} (already merged — skipping)`);
    } else {
      console.log(`Runner deltas:     ${deltaApplied.runId} (merging)`);
    }
  }
  // Use the merged content for parsing — delegate to parseBriefing via tmp shim
  // (parseBriefing reads from a path; we write merged content to a sibling tmp file
  // when a merge actually happened, then parse that).
  let parseInputPath = briefingPath;
  if (deltaApplied && !deltaApplied.alreadyMerged) {
    parseInputPath = path.join(buildOutDir(), ".briefing-merged.tmp.md");
    await fs.writeFile(parseInputPath, merged, "utf-8");
  }
  // Build seen-items.json URL → first_seen map (final date-inference fallback).
  // Reuse the `state` read above — seen-items.json is unchanged between reads.
  const seenUrlDateMap = new Map();
  if (state?.items) {
    for (const it of state.items) {
      if (it.url && it.first_seen) {
        const m = it.first_seen.match(/^(\d{4})-(\d{2})-(\d{2})/);
        if (m) {
          seenUrlDateMap.set(
            it.url,
            Date.UTC(parseInt(m[1], 10), parseInt(m[2], 10) - 1, parseInt(m[3], 10)),
          );
        }
      }
    }
  }
  const briefing = await parseBriefing(parseInputPath, { seenUrlDateMap });
  console.log(`Seen-items dates:  ${seenUrlDateMap.size} URL→date entries (final fallback)`);
  if (parseInputPath !== briefingPath) {
    try { await fs.unlink(parseInputPath); } catch { /* ignore */ }
  }

  // Window from briefing.md header (preferred — reflects actual data)
  if (briefing.meta.window) {
    // briefing.meta.window e.g. "2026-04-24T19:00:00Z → 2026-05-05T20:30:00Z (~11 days)"
    const m = briefing.meta.window.match(/([0-9T:Z\-]+)\s*[→-]+\s*([0-9T:Z\-]+)/);
    if (m) windowStr = formatWindow(m[1], m[2]);
    else windowStr = briefing.meta.window;
  } else if (state?.current_meeting_window?.opened_date) {
    windowStr = formatWindow(state.current_meeting_window.opened_date, new Date().toISOString());
  } else {
    windowStr = `~${dateStr}`;
  }

  // Pre-flight: fetch missing provider logos
  if (!args.noFetchLogos) {
    const fetchResult = await ensureProviderLogos(PROVIDER_LOGOS);
    console.log(`Logos fetched: ${fetchResult.fetched.length} | cached: ${fetchResult.skipped.length} | failed: ${fetchResult.failed.length}`);
    if (fetchResult.failed.length) console.log(`  Failed: ${fetchResult.failed.join(", ")}`);
  }

  // Build context
  const ctx = {
    meetingNumber,
    date: dateStr,
    window: windowStr,
    org: BRAND.org,
  };

  // Emit slides
  const slides = emitSlides(briefing, ctx);

  const meta = {
    meetingNumber,
    org: BRAND.org,
    tagline: BRAND.tagline,
    date: dateStr,
    window: windowStr,
    logoColor: BRAND.logoColor,
    logoWhite: BRAND.logoWhite,
  };

  // Validate before writing
  const deck = { meta, theme: THEME, providerLogos: PROVIDER_LOGOS, slides };
  validateDeck(deck);

  const outPath = args.out
    ? path.resolve(args.out)
    : slidesDataPath();
  await fs.writeFile(outPath, renderModule(deck), "utf-8");

  console.log(`\nSlides emitted:    ${outPath}`);
  console.log(`Slide count:       ${slides.length}`);
  console.log(`Meeting #:         ${meetingNumber}`);
  console.log(`Date:              ${dateStr}`);
  console.log(`Window:            ${windowStr}`);

  // Slide count budget — 60-min meeting / ~1.1min/slide ≈ 55 max comfortable.
  // Warn (not block) so the author can cut LOW items or merge condensed slides.
  const SLIDE_BUDGET_WARN = 55;
  if (slides.length > SLIDE_BUDGET_WARN) {
    console.warn(`\n⚠ Slide count ${slides.length} > budget ${SLIDE_BUDGET_WARN}.`);
    console.warn(`  60-min meeting target ≈ 1.1 min/slide. Consider cutting LOW items or merging condensed slides.`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
