Notes from a season of running the Hollin Street community kiln, written up for anyone who wants to
start one.

We fired forty-one times between March and October. The first six firings went badly: the kiln
shelves were the cheap kind and two cracked under a full load of planters. We replaced them with
silicon carbide shelves, which cost more than the kiln itself but have not moved since.

Scheduling mattered more than any equipment. We kept a shared calendar with fixed slots on
Tuesday and Saturday evenings, and anyone who missed loading their pieces by six waited for the
next slot. That one rule ended most of the arguments.

Glazes were the second lesson. We stocked four base glazes and let people mix from them, and we
kept a test tile for every mix on a board by the door. By September the board held over two
hundred tiles, and newcomers chose from it instead of guessing.

Money: membership was twelve pounds a month, which covered electricity, shelves and clay
reclaim with a little left for a second wheel. We publish the accounts on the noticeboard every
quarter.

If you start one, begin with the calendar and the test-tile board. Everything else can wait.
MD
