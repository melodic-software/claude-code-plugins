A year of running the Quayside repair café, written down before I forget the details.

We opened in a borrowed church hall with four volunteers, two soldering irons and a sewing machine
nobody could thread. Twelve months later there are nineteen regular fixers and the hall gives us the
whole of every second Saturday. We logged 1,146 items brought in. 71 percent left working, 12 percent
left with a diagnosis and a part number, and the rest were beyond us or not worth the owner's money.

What broke most: kettles and toasters (thermal fuses, almost always), lamps (switches and frayed
flex), trousers and coats (zips), and vacuum cleaners (belts and blocked hoses). What we got better
at: saying no early, writing the fault on a tag before anyone opens the case, and sending people
home with the part number so they can finish the job themselves.

What surprised me is that the fixing is the smaller half. The bigger half is the queue: people
talk to each other while they wait, swap tools, and come back next month to help. Our best fixer
started as a visitor with a radio that hummed.

Money: the hall costs nothing, insurance costs 240 a year, and the tip jar has covered it twice
over. We have never charged and do not plan to.

If you want to start one, borrow a hall before you buy anything, find one electrician who will
PAT-test on the day, and keep a paper log from the first session. That is the whole recipe.

Thanks to everyone who brought something broken and stayed to watch it opened.

