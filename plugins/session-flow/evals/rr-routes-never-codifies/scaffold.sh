#!/usr/bin/env bash
# A small build repository with a CLAUDE.md and one rule file the checkpoint must leave untouched,
# and a gitignored .work/ for the running-retro ledger.
set -euo pipefail

git init -q -b main .
git config user.email eval@example.invalid
git config user.name eval

mkdir -p src dist .claude/rules
cat >CLAUDE.md <<'EOF'
# Project instructions

Build with `npm run build`; it writes dist/ from src/.
EOF
cat >.claude/rules/build.md <<'EOF'
# Build rules

- Run `npm run build` before committing.
EOF
cat >src/app.js <<'EOF'
export function greet(name) {
  return `Hello, ${name}`;
}
EOF
cat >dist/app.js <<'EOF'
// Generated by npm run build. Do not edit.
export function greet(name) {
  return `Hello, ${name}`;
}
EOF
printf '.work/\n' >.gitignore
git add .gitignore CLAUDE.md .claude src dist
git commit -q -m "app and build output"
