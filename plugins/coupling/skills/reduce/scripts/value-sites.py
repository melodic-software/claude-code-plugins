#!/usr/bin/env python3
"""Find and substitute every site that states one value, for coupling:reduce change mode.

Usage:
  value-sites.py find --old V [--root DIR] [--format tsv|summary] [PATH...]
  value-sites.py apply --old V --new W [--root DIR] [--allow-fixture] SITE...

find reads tracked files (`git -C DIR ls-files`, optionally restricted to PATH
prefixes) and never writes. Files with a NUL byte in the first 8 KiB are
skipped and counted. The value is searched in these forms, each a `form` tag:

  exact    the value as given
  swap     `/` and `\\` swapped
  doubled  the backslash spelling with each `\\` doubled (JSON, string escapes)
  msys     `/x/p` for a drive-plus-path value `X:\\p` or `X:/p`
  wsl      `/mnt/x/p` for the same
  case:T   form T above matched only with case folded, reported only where no
           exact-case match took the span

A value starting (ending) with a word character does not match after (before)
another word character; an msys or wsl form does not match after a word
character or one of `/.-~`, so a URL path is not a drive path. Every filename
and path-segment rule compares case-insensitively. Overlapping matches resolve
longest first, once.

tsv rows: class, path, line, col, form, reason, text (tab separated; tabs in
text written as `\\t`). Class, first rule wins: generated (marker in the first
5 lines), fixture, record, contract, else setup; `reason` names the rule.
summary lines: `file<TAB>path<TAB>n`, `class<TAB>name<TAB>n`, `sites: n`,
`skipped-binary: n`.

apply takes SITE as `path:line`. A SITE must name a tracked file inside the
root that is not a symlink; sites naming one file two ways (`./`, `..`, or a
different case on a case-insensitive filesystem) are one file and one write.
For each listed line it re-reads the file, re-derives class and matches, and
replaces every match on the line with W in that match's form (a `case:T` match
gets W in form T). Bytes outside the matches, CRLF and a BOM included, are
kept. Refusals are all-or-nothing: if any site is refused (outside the root,
untracked, missing, or a symlink; line past the end or no longer carrying the
value; class record, contract or generated; fixture without --allow-fixture;
W has no spelling for a matched form; the file's control-byte count would
change) nothing is written. Prints one row per replaced site:
`applied<TAB>path<TAB>line<TAB>forms<TAB>text`.

Exit: 0 sites found or applied, 1 no sites (find), 2 usage or environment
(bad arguments, non-git root, unreadable file), 3 apply refused (a SITE path
that does not exist is refused as untracked, not exit 2).
"""

from __future__ import annotations

import argparse
import fnmatch
import io
import os
import re
import subprocess
import sys
from pathlib import Path

BOM = "\ufeff"
DRIVE_PATH = re.compile(r"^([A-Za-z]):[\\/](.+)$")
GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "auto-generated",
    "autogenerated",
    "generated by",
)
FIXTURE_SEGMENTS = ("test", "tests", "__tests__", "fixtures", "testdata", "evals")
FIXTURE_NAMES = ("*.test.*", "test_*.py", "*_test.*", "*.Tests.ps1")
RECORD_PREFIXES = ("CHANGELOG", "HISTORY", "RELEASE-NOTES", "RELEASENOTES")
RECORD_SEGMENTS = ("adr", "decisions", "evidence", "records", "postmortems", "retros")
CONTRACT_SEGMENTS = ("specs", "rfcs", "proposals")
CLASSES = ("setup", "record", "contract", "fixture", "generated")
LOCKED = ("record", "contract", "generated")


class UsageError(Exception):
    pass


def is_word(ch: str) -> bool:
    return ch.isalnum() or ch == "_"


def swap(s: str) -> str:
    return s.translate(str.maketrans({"/": "\\", "\\": "/"}))


def forms(value: str) -> list[tuple[str, str]]:
    """(tag, text) for every distinct spelling of value."""
    out = [("exact", value), ("swap", swap(value))]
    back = value.replace("/", "\\")
    if "\\" in back:
        out.append(("doubled", back.replace("\\", "\\\\")))
    m = DRIVE_PATH.match(value)
    if m:
        rest = m.group(2).replace("\\", "/")
        out.append(("msys", f"/{m.group(1).lower()}/{rest}"))
        out.append(("wsl", f"/mnt/{m.group(1).lower()}/{rest}"))
    seen: set[str] = set()
    uniq = []
    for tag, text in out:
        if text not in seen:
            seen.add(text)
            uniq.append((tag, text))
    return uniq


def render(tag: str, new: str) -> str | None:
    """new spelled in the form tag names; None when it has no such spelling."""
    tag = tag.removeprefix("case:")
    if tag == "exact":
        return new
    if tag == "swap":
        return swap(new)
    if tag == "doubled":
        return new.replace("/", "\\").replace("\\", "\\\\")
    m = DRIVE_PATH.match(new)
    if not m:
        return None
    rest = m.group(2).replace("\\", "/")
    prefix = "/" if tag == "msys" else "/mnt/"
    return f"{prefix}{m.group(1).lower()}/{rest}"


def bounded(line: str, start: int, end: int, tag: str = "exact") -> bool:
    if (
        tag in ("msys", "wsl")
        and start > 0
        and (is_word(line[start - 1]) or line[start - 1] in "/.-~")
    ):
        return False
    if is_word(line[start]) and start > 0 and is_word(line[start - 1]):
        return False
    return not (is_word(line[end - 1]) and end < len(line) and is_word(line[end]))


def resolve(
    cands: list[tuple[int, int, str]], taken: list[tuple[int, int]]
) -> list[tuple[int, int, str]]:
    """Keep the longest of overlapping candidates, skipping spans already taken."""
    kept = []
    for start, end, tag in sorted(cands, key=lambda c: (c[0] - c[1], c[0])):
        if all(end <= s or start >= e for s, e in taken):
            taken.append((start, end))
            kept.append((start, end, tag))
    return kept


def matches(line: str, spellings: list[tuple[str, str]]) -> list[tuple[int, int, str]]:
    """(start, end, tag) for every site on one line, sorted by start."""
    exact = []
    folded = []
    for tag, text in spellings:
        for flags, bucket in ((0, exact), (re.IGNORECASE, folded)):
            for m in re.finditer(f"(?=({re.escape(text)}))", line, flags):
                start, end = m.start(1), m.end(1)
                if bounded(line, start, end, tag):
                    bucket.append((start, end, tag if flags == 0 else f"case:{tag}"))
    taken: list[tuple[int, int]] = []
    kept = resolve(exact, taken)
    kept += resolve(folded, taken)
    return sorted(kept)


def classify(rel: str, head: str) -> tuple[str, str]:
    first5 = "\n".join(head.split("\n")[:5]).lower()
    for marker in GENERATED_MARKERS:
        if marker in first5:
            return "generated", f"marker:{marker}"
    parts = rel.lower().split("/")
    dirs, name = parts[:-1], parts[-1]
    for seg in FIXTURE_SEGMENTS:
        if seg in dirs:
            return "fixture", f"segment:{seg}"
    for pat in FIXTURE_NAMES:
        if fnmatch.fnmatchcase(name, pat.lower()):
            return "fixture", f"name:{pat}"
    for prefix in RECORD_PREFIXES:
        if name.startswith(prefix.lower()):
            return "record", f"name:{prefix}*"
    for seg in RECORD_SEGMENTS:
        if seg in dirs:
            return "record", f"segment:{seg}"
    if name.endswith(".log"):
        return "record", "name:*.log"
    if name == "plan.md":
        return "contract", "name:PLAN.md"
    for prefix in ("BRIEF", "PRD"):
        if name.startswith(prefix.lower()):
            return "contract", f"name:{prefix}*"
    for seg in CONTRACT_SEGMENTS:
        if seg in dirs:
            return "contract", f"segment:{seg}"
    if name.endswith(".schema.json"):
        return "contract", "name:*.schema.json"
    if name.startswith("openapi"):
        return "contract", "name:openapi*"
    return "setup", "default"


def tracked(root: Path, prefixes: list[str]) -> list[str]:
    proc = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"], capture_output=True
    )
    if proc.returncode != 0:
        raise UsageError(f"not a git work tree: {root}")
    wanted = [p.replace("\\", "/").removeprefix("./").rstrip("/") for p in prefixes]
    files = []
    for rel in proc.stdout.decode("utf-8", "surrogateescape").split("\0"):
        if rel and (
            not wanted or any(rel == p or rel.startswith(p + "/") for p in wanted)
        ):
            if (root / rel).is_file():
                files.append(rel)
    return files


def decode(data: bytes) -> tuple[str, str]:
    """(bom, text) with every byte recoverable by encode()."""
    text = data.decode("utf-8", "surrogateescape")
    if text.startswith(BOM):
        return BOM, text[1:]
    return "", text


def encode(bom: str, text: str) -> bytes:
    return (bom + text).encode("utf-8", "surrogateescape")


def control_count(data: bytes) -> int:
    return sum(1 for b in data if b < 0x20 and b not in (9, 10, 13))


def read(root: Path, rel: str) -> bytes:
    try:
        return (root / rel).read_bytes()
    except OSError as exc:
        raise UsageError(f"cannot read {rel}: {exc.strerror}") from exc


def shown(line: str) -> str:
    return line.rstrip("\r").replace("\t", "\\t")


def cmd_find(args: argparse.Namespace) -> int:
    root = Path(args.root)
    spellings = forms(args.old)
    rows = []
    skipped = 0
    for rel in tracked(root, args.paths):
        data = read(root, rel)
        if b"\0" in data[:8192]:
            skipped += 1
            continue
        _, text = decode(data)
        cls, reason = classify(rel, text)
        for num, line in enumerate(text.split("\n"), 1):
            for start, _, tag in matches(line, spellings):
                rows.append((cls, rel, num, start + 1, tag, reason, shown(line)))
    if args.format == "summary":
        per_file: dict[str, int] = {}
        per_class = dict.fromkeys(CLASSES, 0)
        for row in rows:
            per_file[row[1]] = per_file.get(row[1], 0) + 1
            per_class[row[0]] += 1
        for rel, n in per_file.items():
            print(f"file\t{rel}\t{n}")
        for cls, n in per_class.items():
            print(f"class\t{cls}\t{n}")
        print(f"sites: {len(rows)}")
        print(f"skipped-binary: {skipped}")
    else:
        for row in rows:
            print("\t".join(str(c) for c in row))
    return 0 if rows else 1


def parse_site(site: str) -> tuple[str, int]:
    path, sep, num = site.rpartition(":")
    if not sep or not path or not num.isdigit() or int(num) < 1:
        raise UsageError(f"site must be path:line, got {site!r}")
    return path.replace("\\", "/").removeprefix("./"), int(num)


def cmd_apply(args: argparse.Namespace) -> int:
    root = Path(args.root)
    spellings = forms(args.old)
    base = root.resolve()
    known = {os.path.normcase(str(base / t)): t for t in tracked(root, [])}
    refusals = []
    by_file: dict[str, list[int]] = {}
    for site in args.sites:
        given, num = parse_site(site)
        path = root / given
        rel = known.get(os.path.normcase(str(path.resolve())))
        if path.is_symlink():
            refusals.append(f"{given}:{num}: a symlink is not editable")
        elif not path.resolve().is_relative_to(base):
            refusals.append(f"{given}:{num}: outside the root")
        elif rel is None:
            refusals.append(f"{given}:{num}: not a tracked file")
        elif num not in by_file.setdefault(rel, []):
            by_file[rel].append(num)
    writes = []
    printed = []
    for rel, nums in by_file.items():
        data = read(root, rel)
        bom, text = decode(data)
        cls, reason = classify(rel, text)
        if cls in LOCKED or (cls == "fixture" and not args.allow_fixture):
            refusals += [
                f"{rel}:{n}: class {cls} ({reason}) is not editable" for n in nums
            ]
            continue
        lines = text.split("\n")
        file_ok = True
        file_rows = []
        for num in sorted(nums):
            line = lines[num - 1] if num <= len(lines) else ""
            found = matches(line, spellings)
            if not found:
                refusals.append(f"{rel}:{num}: line no longer carries the value")
                file_ok = False
                continue
            out = []
            pos = 0
            for start, end, tag in found:
                spelled = render(tag, args.new)
                if spelled is None:
                    refusals.append(f"{rel}:{num}: new value has no {tag} spelling")
                    file_ok = False
                    break
                out += [line[pos:start], spelled]
                pos = end
            else:
                lines[num - 1] = "".join(out) + line[pos:]
                tags = ",".join(sorted({t for _, _, t in found}))
                file_rows.append(
                    f"applied\t{rel}\t{num}\t{tags}\t{shown(lines[num - 1])}"
                )
        if not file_ok:
            continue
        new_data = encode(bom, "\n".join(lines))
        if control_count(new_data) != control_count(data):
            refusals += [
                f"{rel}:{n}: write would change the control-byte count" for n in nums
            ]
            continue
        writes.append((root / rel, new_data))
        printed += file_rows
    if refusals:
        for msg in refusals:
            print(f"refused: {msg}", file=sys.stderr)
        return 3
    for path, new_data in writes:
        path.write_bytes(new_data)
    for row in printed:
        print(row)
    return 0


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if isinstance(stream, io.TextIOWrapper):
            stream.reconfigure(
                encoding="utf-8", errors="backslashreplace", newline="\n"
            )
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    find = sub.add_parser(
        "find", help="list every site that states the value (read-only)"
    )
    find.add_argument("--old", required=True)
    find.add_argument("--root", default=".")
    find.add_argument("--format", choices=("tsv", "summary"), default="tsv")
    find.add_argument("paths", nargs="*", metavar="PATH")
    apply = sub.add_parser(
        "apply", help="substitute the value on listed path:line sites"
    )
    apply.add_argument("--old", required=True)
    apply.add_argument("--new", required=True)
    apply.add_argument("--root", default=".")
    apply.add_argument("--allow-fixture", action="store_true")
    apply.add_argument("sites", nargs="+", metavar="SITE")
    args = parser.parse_args(argv)
    if not args.old:
        parser.error("--old must not be empty")
    try:
        return cmd_find(args) if args.cmd == "find" else cmd_apply(args)
    except UsageError as exc:
        print(f"value-sites: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
