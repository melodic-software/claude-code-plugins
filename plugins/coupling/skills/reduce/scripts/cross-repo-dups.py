#!/usr/bin/env python3
"""Find files copied between repositories, for coupling:reduce at the repository altitude.

Usage:
  cross-repo-dups.py [--ref REF] [--managed FILE]... [--repos-from FILE] [REPO...]

REPO is a checkout path, or LABEL=PATH. Without a label, the label is the
`owner/name` its origin URL names, else the folder name. --repos-from reads more
REPOs, one per line, from FILE (`-` is stdin). At least two repositories are
needed. Each repository is read at REF (default `origin/HEAD`, else `HEAD`), from
its object store only: the working tree is never read, nothing is fetched, and
nothing is written.

A copy a mechanism already owns is not a finding. These are excluded before
grouping, and counted:
  managed    a path listed in a --managed FILE: one entry per line, `LABEL:PATH`
             for one repository or a bare `PATH` for every one; `#` starts a
             comment. Give it a sync manifest's destinations, or a vendoring
             registry's copies.
  generated  a file whose first 5 lines say it is generated (`generated from`,
             `generated by`, `do not edit`).
  path       fixtures, test data, snapshots, vendor and node_modules trees.

Rows, tab-separated:
  ref        LABEL  REF                      the commit each repository was read at
  exact      REPOS  COPIES  LIST             one blob tracked in 2 or more repositories
  diverged   REPOS  VARIANTS  SIMILARITY  NAME  LIST
                                             one file name in 2 or more repositories
                                             with differing content; SIMILARITY is the
                                             lowest line similarity (0.00-1.00) of a
                                             variant to the most common one, `?` when a
                                             variant was too large to compare
  excluded   REASON  COUNT                   files dropped per reason above
  skip       LABEL  REASON                   a repository that could not be read

LIST is `LABEL:PATH` entries joined by ` | `. Exit 0 on success, 2 on a usage
error or fewer than 2 readable repositories.
"""

import argparse
import collections
import difflib
import os
import re
import subprocess
import sys

SKIP_PATH = re.compile(
    r"(^|/)(fixtures?|test-data|testdata|__snapshots__|snapshots|vendor|node_modules)/"
)
GENERATED = re.compile(r"generated (from|by)|do not edit", re.I)
NAMES_EVERY_REPO_OWNS = {
    "README.md",
    "CHANGELOG.md",
    "AGENTS.md",
    "CLAUDE.md",
    "LICENSE",
    "SECURITY.md",
    "CODEOWNERS",
    "index.md",
    "SKILL.md",
    "package.json",
    "package-lock.json",
    "plugin.json",
    "marketplace.json",
    "tsconfig.json",
    "config.json",
    "settings.json",
    "action.yml",
    "dependabot.yml",
    "lefthook.yml",
    ".gitignore",
    ".gitattributes",
    ".editorconfig",
    "main.go",
    "test.sh",
    "__init__.py",
}
MAX_BYTES = 200_000
MAX_VARIANTS = 12


def git(path, *args):
    r = subprocess.run(["git", "-C", path, *args], capture_output=True)
    return r.returncode, r.stdout


def label_for(path):
    rc, out = git(path, "remote", "get-url", "origin")
    if rc == 0:
        m = re.search(r"[:/]([^/:]+/[^/]+?)(\.git)?/?$", out.decode().strip())
        if m:
            return m.group(1)
    return os.path.basename(os.path.abspath(path))


def resolve_ref(path, ref):
    for cand in [ref] if ref else ["origin/HEAD", "HEAD"]:
        rc, out = git(path, "rev-parse", "--verify", "-q", cand + "^{commit}")
        if rc == 0:
            return cand, out.decode().strip()
    return None, None


def blobs(path, commit):
    rc, out = git(path, "ls-tree", "-r", "-z", commit)
    if rc != 0:
        return
    for rec in out.split(b"\0"):
        if not rec:
            continue
        meta, name = rec.split(b"\t", 1)
        _, kind, sha = meta.split()
        if kind == b"blob":
            yield sha.decode(), name.decode("utf-8", "surrogateescape")


def read_blob(path, sha, limit=None):
    rc, out = git(path, "cat-file", "blob", sha)
    if rc != 0 or (limit and len(out) > limit):
        return None
    return out


def load_managed(files):
    any_repo, per_repo = set(), set()
    for f in files:
        with open(f, encoding="utf-8") as fh:
            for line in fh:
                line = line.split("#", 1)[0].strip()
                if not line:
                    continue
                label, sep, rest = line.partition(":")
                if sep and "/" in label and rest:
                    per_repo.add((label, rest.lstrip("/")))
                else:
                    any_repo.add(line.lstrip("/"))
    return any_repo, per_repo


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("--ref")
    ap.add_argument("--managed", action="append", default=[])
    ap.add_argument("--repos-from")
    ap.add_argument("repos", nargs="*")
    a = ap.parse_args()

    specs = list(a.repos)
    if a.repos_from:
        fh = sys.stdin if a.repos_from == "-" else open(a.repos_from, encoding="utf-8")
        specs += [
            line.strip() for line in fh if line.strip() and not line.startswith("#")
        ]
    try:
        managed_any, managed_repo = load_managed(a.managed)
    except OSError as e:
        print(f"cross-repo-dups.py: {e}", file=sys.stderr)
        return 2

    repos = {}
    for spec in specs:
        label, sep, path = spec.partition("=")
        if not sep:
            label, path = None, spec
        if not os.path.isdir(path):
            print(f"skip\t{label or path}\tnot a directory")
            continue
        label = label or label_for(path)
        if label in repos:
            print(f"skip\t{label}\tduplicate label")
            continue
        used, commit = resolve_ref(path, a.ref)
        if not commit:
            print(f"skip\t{label}\tno {a.ref or 'origin/HEAD or HEAD'} commit")
            continue
        repos[label] = (path, commit)
        print(f"ref\t{label}\t{used}")
    if len(repos) < 2:
        print(
            "cross-repo-dups.py: need at least 2 readable repositories", file=sys.stderr
        )
        return 2

    excluded = collections.Counter()
    rows = []
    for label, (path, commit) in repos.items():
        for sha, name in blobs(path, commit):
            if name in managed_any or (label, name) in managed_repo:
                excluded["managed"] += 1
            elif SKIP_PATH.search(name):
                excluded["path"] += 1
            else:
                rows.append((sha, label, name))

    head_cache = {}

    def generated(sha, label):
        if sha not in head_cache:
            data = read_blob(repos[label][0], sha) or b""
            head = b"\n".join(data.split(b"\n", 5)[:5]).decode("utf-8", "replace")
            head_cache[sha] = bool(GENERATED.search(head))
        return head_cache[sha]

    by_blob = collections.defaultdict(list)
    by_name = collections.defaultdict(list)
    for sha, label, name in rows:
        by_blob[sha].append((label, name))
        base = os.path.basename(name)
        if base not in NAMES_EVERY_REPO_OWNS:
            by_name[base].append((sha, label, name))

    exact = []
    for sha, copies in by_blob.items():
        if len({lab for lab, _ in copies}) < 2:
            continue
        if generated(sha, copies[0][0]):
            excluded["generated"] += len(copies)
            continue
        labels = {lab for lab, _ in copies}
        exact.append(
            (
                len(labels),
                len(copies),
                " | ".join(f"{lab}:{p}" for lab, p in sorted(copies)),
            )
        )
    for n_repos, n_copies, listing in sorted(exact, key=lambda r: (-r[0], -r[1], r[2])):
        print(f"exact\t{n_repos}\t{n_copies}\t{listing}")

    diverged = []
    for base, copies in by_name.items():
        copies = [c for c in copies if not generated(c[0], c[1])]
        labels = {lab for _, lab, _ in copies}
        shas = collections.Counter(s for s, _, _ in copies)
        if len(labels) < 2 or len(shas) < 2:
            continue
        owner = {s: lab for s, lab, _ in copies}
        mode = shas.most_common(1)[0][0]
        base_text = read_blob(repos[owner[mode]][0], mode, MAX_BYTES)
        sims = []
        for s, _ in shas.most_common(MAX_VARIANTS):
            if s == mode:
                continue
            other = read_blob(repos[owner[s]][0], s, MAX_BYTES)
            if base_text is None or other is None:
                sims.append(None)
                continue
            a_lines = base_text.decode("utf-8", "replace").splitlines()
            b_lines = other.decode("utf-8", "replace").splitlines()
            sims.append(
                difflib.SequenceMatcher(None, a_lines, b_lines, autojunk=False).ratio()
            )
        sim = "?" if None in sims or not sims else f"{min(sims):.2f}"
        listing = " | ".join(
            f"{lab}:{p}" for _, lab, p in sorted(copies, key=lambda c: (c[1], c[2]))
        )
        diverged.append((len(labels), len(shas), sim, base, listing))
    for n_repos, n_var, sim, base, listing in sorted(
        diverged, key=lambda r: (-r[0], -(float(r[2]) if r[2] != "?" else -1), r[3])
    ):
        print(f"diverged\t{n_repos}\t{n_var}\t{sim}\t{base}\t{listing}")

    for reason in ("managed", "generated", "path"):
        print(f"excluded\t{reason}\t{excluded[reason]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
