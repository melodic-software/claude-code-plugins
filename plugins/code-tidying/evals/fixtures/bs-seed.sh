#!/usr/bin/env bash
# The seeded files hold literal $ expansions and backticks, so single quotes are intended.
# shellcheck disable=SC2016
# Seeds the eval workspace (the current directory) with a small bash repository whose history
# makes every batch-simplify scope resolve to a known file set. Commit dates are set relative to
# now through GIT_AUTHOR_DATE / GIT_COMMITTER_DATE, so the windows hold whenever the case runs.
#
#   main      C1  40d ago  initial tree (src/greet.sh still says say_hello, src/legacy.sh bait)
#   main      C2  35d ago  lib/old.sh                                   <- branch point
#   feature   B1  10d ago  src/helpers.sh, lib/branch-util.sh
#   feature   B2  20h ago  src/greet.sh (rename + bait), repo/tool.sh, vendor/gen.sh,
#                          .github/workflows/ci.yml, CHANGELOG.md, docs/guide.md,
#                          docs/history-log.md, docs/adr/0001-greeting-function.md, tests/run.sh
#   main      M3  30h ago  src/legacy.sh header comment (main only, after the branch point)
#
# HEAD ends on feature/tidy. Every bait script carries an if/else whose two arms are identical.
#
# Usage: bs-seed.sh [--dirty]   --dirty leaves an uncommitted edit in tracked src/greet.sh
set -euo pipefail

fixtures="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
now="$(date +%s)"

put() { # put <fixture-name> <destination>
  mkdir -p "$(dirname "$2")"
  cp "$fixtures/$1.txt" "$2"
}

commit_hours_ago() { # commit_hours_ago <hours> <message>
  local stamp="$((now - $1 * 3600)) +0000"
  git add -A
  GIT_AUTHOR_DATE="$stamp" GIT_COMMITTER_DATE="$stamp" \
    git -c user.name=eval -c user.email=eval@example.invalid commit -q -m "$2"
}

git init -q
git symbolic-ref HEAD refs/heads/main

# C1: initial tree, with earlier versions of the files B2 later changes.
put bs-CLAUDE.md CLAUDE.md
put bs-legacy.sh src/legacy.sh
mkdir -p src repo vendor .github/workflows docs tests
printf '%s\n' '#!/usr/bin/env bash' '# Prints a greeting for the given name.' 'set -euo pipefail' '' \
  'say_hello() {' '  printf '"'"'Hello, %s!\n'"'"' "${1:-world}"' '}' '' 'say_hello "$@"' >src/greet.sh
printf '%s\n' '#!/usr/bin/env bash' '# Reports how many items the tool processed.' 'set -euo pipefail' '' \
  'echo "tool: processed ${1:-0} items"' >repo/tool.sh
printf '%s\n' '#!/usr/bin/env bash' '# GENERATED by scripts/regen-vendor.sh from upstream. DO NOT EDIT: changes are overwritten on the next regeneration.' \
  'set -euo pipefail' '' 'echo "gen: target is ${1:-all}"' >vendor/gen.sh
printf '%s\n' 'name: ci' 'on: [push]' 'jobs:' '  test:' '    runs-on: ubuntu-latest' '    steps:' \
  '      - uses: actions/checkout@v4' '      - run: bash tests/run.sh' >.github/workflows/ci.yml
printf '%s\n' '# Changelog' '' '## 0.1.0' '- Added `say_hello` greeting script.' >CHANGELOG.md
printf '%s\n' '# Guide' '' 'Inside your own scripts, call `say_hello NAME` to print a greeting.' >docs/guide.md
printf '%s\n' '# Release history' '' 'This log is append-only. Do not edit historical entries; add a new one instead.' '' \
  '- 0.1.0: introduced `say_hello`.' >docs/history-log.md
printf '%s\n' '#!/usr/bin/env bash' 'echo "all tests passed"' >tests/run.sh
commit_hours_ago 960 "feat: initial greeter toolkit"

# C2: the branch point.
put bs-old.sh lib/old.sh
commit_hours_ago 840 "feat: add old status script"

git checkout -q -b feature/tidy

# B1: ten days old, on the branch only.
put bs-helpers.sh src/helpers.sh
put bs-branch-util.sh lib/branch-util.sh
commit_hours_ago 240 "feat: add helper and branch utility scripts"

# B2: inside every time window the cases use.
put bs-greet.sh src/greet.sh
put bs-tool.sh repo/tool.sh
put bs-gen.sh vendor/gen.sh
put bs-ci.yml .github/workflows/ci.yml
put bs-CHANGELOG.md CHANGELOG.md
put bs-guide.md docs/guide.md
put bs-history-log.md docs/history-log.md
put bs-adr-0001.md docs/adr/0001-greeting-function.md
put bs-run-tests.sh tests/run.sh
commit_hours_ago 20 "refactor: rename say_hello to greet and extend scripts"

# M3: a main-only change after the branch point, to a file the branch never touched.
git checkout -q main
sed -i.bak 's/# Prints the legacy status\./# Prints the legacy flag status./' src/legacy.sh
rm -f src/legacy.sh.bak
commit_hours_ago 30 "docs: clarify legacy header"
git checkout -q feature/tidy

if [[ "${1:-}" = "--dirty" ]]; then
  printf '%s\n' '# WIP-KEEP: half-written retry flag, not committed yet' >>src/greet.sh
fi
