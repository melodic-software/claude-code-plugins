CONV_HEADING = "\n## Developer tooling conventions\n\n"


def write_tree(root, files):
    for rel, body in files.items():
        if body is None:
            continue
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")
        if rel.endswith(".sh"):
            path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def make_sln(root):
    subprocess.run(
        ["dotnet", "new", "sln", "-n", "Tarnquill", "--format", "sln"],
        cwd=root, check=True, capture_output=True,
    )
    subprocess.run(
        ["dotnet", "sln", "Tarnquill.sln", "add",
         "src/Tarnquill.Cli/Tarnquill.Cli.csproj",
         "src/Tarnquill.Core/Tarnquill.Core.csproj",
         "tests/Tarnquill.Core.Checks/Tarnquill.Core.Checks.csproj"],
        cwd=root, check=True, capture_output=True,
    )


def pointer(root, conv_path):
    proc = subprocess.run(
        ["bash", str(HELPER), "apply", "--root", str(root), "--path", conv_path, "--yes"],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit(1)


def state_dir(name, state):
    path = FIXTURES / name / state
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)
    return path


def build(name, files, agents_bare, conv_sections, conv_file, sln):
    for state in ("bare", "conventions-only", "converged"):
        root = state_dir(name, state)
        write_tree(root, files)
        if sln:
            make_sln(root)
        agents = agents_bare
        if state == "conventions-only":
            agents = agents_bare + CONV_HEADING + conv_sections
        (root / "AGENTS.md").write_text(agents, encoding="utf-8", newline="\n")
        if state == "converged":
            conv = root / "docs/conventions/developer-experience.md"
            conv.parent.mkdir(parents=True)
            conv.write_text(conv_file, encoding="utf-8", newline="\n")
            pointer(root, "docs/conventions/developer-experience.md")


