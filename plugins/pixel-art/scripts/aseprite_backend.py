"""Build an Aseprite sprite from a spec and export a real Aseprite sheet.

The Lua script is the authoring step (`--batch --script`). A second `--batch`
invocation exports `--sheet` and `--data --format json-hash`. Preview and GIFs
stay on the native renderer so those files keep the plugin's shape.
"""
import json
import render


def lua_long_string(text):
    level = 0
    while True:
        eq = "=" * level
        closer = "]" + eq + "]"
        if closer not in text:
            return "[" + eq + "[" + text + "]" + eq + "]"
        level += 1


def sheet_order(spec):
    frames = spec["frames"]
    order = spec.get("sheet", {}).get("order") or list(frames)
    if not order:
        order = list(frames)
    return order


def export_plan(spec):
    """Frames in sheet order, including null cells as empty frames, plus tags."""
    spec = render.palette_mod.prepare_spec(spec, None) if isinstance(spec.get("palette"), str) else spec
    width, height = render.validate(spec)
    order = sheet_order(spec)
    durations = {}
    for anim in spec.get("animations", {}).values():
        for name, ms in zip(anim["frames"], render.frame_durations(anim)):
            durations[name] = ms
    frames = []
    index = {}
    for slot, name in enumerate(order, start=1):
        if name is None:
            frames.append({"name": None, "rows": None, "duration_ms": 100})
            continue
        index[name] = slot
        frames.append({
            "name": name,
            "rows": spec["frames"][name],
            "duration_ms": durations.get(name, 100),
        })
    tags, split = [], []
    for name, anim in spec.get("animations", {}).items():
        slots = [index[frame] for frame in anim["frames"] if frame in index]
        if not slots:
            continue
        lo, hi = min(slots), max(slots)
        if sorted(slots) != list(range(lo, hi + 1)):
            split.append(name)   # an Aseprite tag is one from/to range; the caller falls back to native
            continue
        tags.append({"name": name, "from": lo, "to": hi})
    columns = spec.get("sheet", {}).get("columns") or len(order)
    return {
        "palette": spec["palette"],
        "width": width,
        "height": height,
        "columns": columns,
        "frames": frames,
        "tags": tags,
        "noncontiguous": split,
    }


def build_lua(spec):
    """Lua for `aseprite --batch --script`. Reads `app.params.ase` as the save path."""
    plan = export_plan(spec)
    payload = lua_long_string(json.dumps(plan, separators=(",", ":")))
    return f"""-- Generated by pixel-art aseprite_backend.py. Aseprite scripting API.
local plan = json.decode({payload})
local sprite = Sprite(plan.width, plan.height, ColorMode.RGB)
local layer = sprite.layers[1]
for i, frame in ipairs(plan.frames) do
  if i > 1 then
    sprite:newEmptyFrame(i)
  end
  local image = Image(plan.width, plan.height, ColorMode.RGB)
  image:clear()
  if frame.rows ~= nil then
    for y, row in ipairs(frame.rows) do
      for x = 1, #row do
        local ch = row:sub(x, x)
        local hex = plan.palette[ch]
        if hex ~= nil then
          local h = hex:gsub("#", "")
          local r = tonumber(h:sub(1, 2), 16)
          local g = tonumber(h:sub(3, 4), 16)
          local b = tonumber(h:sub(5, 6), 16)
          image:drawPixel(x - 1, y - 1, app.pixelColor.rgba(r, g, b, 255))
        end
      end
    end
  end
  local cel = layer:cel(i)
  if cel == nil then
    sprite:newCel(layer, i, image, Point(0, 0))
  else
    cel.image = image
  end
  sprite.frames[i].duration = frame.duration_ms / 1000
end
for _, tagPlan in ipairs(plan.tags) do
  local tag = sprite:newTag(tagPlan["from"], tagPlan["to"])
  tag.name = tagPlan.name
end
sprite:saveAs(app.params["ase"])
sprite:close()
"""


def script_argv(executable, lua_path, ase_path, spec_path):
    # Aseprite processes CLI arguments in order: a --script-param after --script
    # is not set yet when the script runs.
    return [
        executable, "--batch",
        "--script-param", f"ase={ase_path}",
        "--script-param", f"spec={spec_path}",
        "--script", str(lua_path),
    ]


def export_argv(executable, ase_path, sheet_path, data_path, columns):
    return [
        executable, "--batch", str(ase_path),
        "--sheet", str(sheet_path),
        "--data", str(data_path),
        "--format", "json-hash",
        "--list-tags",
        "--sheet-type", "rows",
        "--sheet-columns", str(columns),
    ]
