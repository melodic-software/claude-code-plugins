#!/usr/bin/env bash
# Regression tests for lib/index-regen.sh — the shared slice-index regeneration
# script (topic-docs v3, design-threads.md T1-T5).
# Run directly: bash lib/index-regen.test.sh
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT="$SCRIPT_DIR/index-regen.sh"

TEST_TMPDIR="$(mktemp -d)"
trap 'rm -rf "$TEST_TMPDIR"' EXIT

BEGIN_MARKER='<!-- BEGIN GENERATED: slice index — regenerated by the shared lib script; edits inside are lost -->'
END_MARKER='<!-- END GENERATED: slice index -->'

FAILED=0
CASE_NUM=0

pass() {
  CASE_NUM=$((CASE_NUM + 1))
  printf 'PASS: %s\n' "$1"
}
fail() {
  CASE_NUM=$((CASE_NUM + 1))
  FAILED=$((FAILED + 1))
  printf 'FAIL: %s\n  detail: %s\n' "$1" "$2" >&2
}
assert_eq() {
  if [[ "$2" == "$3" ]]; then pass "$1"; else fail "$1" "expected: [$2], actual: [$3]"; fi
}
assert_exit() {
  if [[ "$2" == "$3" ]]; then pass "$1"; else fail "$1" "expected exit $2, got $3"; fi
}
assert_contains() {
  case "$2" in
  *"$3"*) pass "$1" ;;
  *) fail "$1" "expected to contain: [$3], actual: [$2]" ;;
  esac
}
assert_not_contains() {
  case "$2" in
  *"$3"*) fail "$1" "expected NOT to contain: [$3]" ;;
  *) pass "$1" ;;
  esac
}

# Build a slice INDEX.md with the standard frontmatter and a stale generated
# body. $1 = slice dir; remaining args = child names for the children list.
write_slice_index() {
  local dir="$1"
  shift
  mkdir -p "$dir"
  {
    printf '%s\n' '---'
    printf '%s\n' 'slice: fixture'
    printf '%s\n' 'abstract: "Fixture slice one-liner"'
    printf '%s\n' 'status: active'
    printf '%s\n' 'children:'
    local c
    for c in "$@"; do
      printf '  - %s\n' "$c"
    done
    printf '%s\n' '---'
    printf '%s\n' ''
    printf '%s\n' '# Fixture slice'
    printf '%s\n' ''
    printf '%s\n' "$BEGIN_MARKER"
    printf '%s\n' 'STALE BODY LINE'
    printf '%s\n' "$END_MARKER"
    printf '%s\n' ''
    printf '%s\n' 'Tail prose stays put.'
  } >"$dir/INDEX.md"
}

# Child slice with its own INDEX.md carrying the given abstract line (written
# raw, so callers can pass quoted or unquoted scalars).
write_child_index() {
  local dir="$1" abstract_raw="$2"
  mkdir -p "$dir"
  {
    printf '%s\n' '---'
    printf 'abstract: %s\n' "$abstract_raw"
    printf '%s\n' 'status: active'
    printf '%s\n' '---'
    printf '%s\n' 'child body'
  } >"$dir/INDEX.md"
}

# Index-less leaf: one reserved artifact with a header abstract.
write_leaf_artifact() {
  local dir="$1" artifact="$2" abstract_raw="$3"
  mkdir -p "$dir"
  {
    printf '%s\n' '---'
    printf 'abstract: %s\n' "$abstract_raw"
    printf '%s\n' '---'
    printf '%s\n' 'leaf notes'
  } >"$dir/$artifact"
}

# Extract the lines strictly between the markers.
generated_body() {
  awk -v b="$BEGIN_MARKER" -v e="$END_MARKER" '
    $0 == e { on = 0 }
    on { print }
    $0 == b { on = 1 }
  ' "$1/INDEX.md"
}

run_script() {
  bash "$SCRIPT" "$@" 2>&1
}

# --- --help: side-effect-free exit 0, documents the contract -----------------
rc=0
OUT=$(bash "$SCRIPT" --help) || rc=$?
assert_exit "--help exits 0" 0 "$rc"
assert_contains "--help documents usage" "$OUT" "index-regen.sh <slice-dir>"
assert_contains "--help documents exit 1" "$OUT" "parity mismatch"
assert_contains "--help documents exit 2" "$OUT" "duplicated markers"
assert_contains "--help documents exit 3" "$OUT" "size cap"
assert_contains "--help documents the cap env var" "$OUT" "INDEX_REGEN_MAX_BYTES"
assert_contains "--help documents the precedence chain" "$OUT" "EXPLORE.md > RESEARCH.md > INTENT.md"

# --- usage errors exit 2 ------------------------------------------------------
rc=0
run_script >/dev/null || rc=$?
assert_exit "no args exits 2" 2 "$rc"
rc=0
run_script "$TEST_TMPDIR/absent-dir" >/dev/null || rc=$?
assert_exit "nonexistent slice dir exits 2" 2 "$rc"

# --- happy regen --------------------------------------------------------------
S="$TEST_TMPDIR/happy"
write_slice_index "$S" alpha beta
write_child_index "$S/alpha" '"Alpha child one-liner"'
write_child_index "$S/beta" 'Beta child one-liner'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "happy regen exits 0" 0 "$rc"
assert_contains "happy regen reports regeneration" "$OUT" "regenerated: $S/INDEX.md (2 children)"
assert_contains "happy regen reports parity ok" "$OUT" "parity: ok (2 declared, 2 on disk)"
BODY=$(generated_body "$S")
assert_contains "body lists alpha with its entry point" "$BODY" "[alpha](alpha/INDEX.md)"
assert_contains "body lists beta with its entry point" "$BODY" "[beta](beta/INDEX.md)"
assert_not_contains "stale body was replaced" "$BODY" "STALE BODY LINE"
FULL=$(cat "$S/INDEX.md")
assert_contains "frontmatter is preserved" "$FULL" 'abstract: "Fixture slice one-liner"'
assert_contains "prose outside the markers is preserved" "$FULL" "Tail prose stays put."
# Second run is a no-op.
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "idempotent second run exits 0" 0 "$rc"
assert_contains "idempotent second run reports unchanged" "$OUT" "unchanged: $S/INDEX.md"

# --- ordering follows the declared children list, not disk order -------------
S="$TEST_TMPDIR/order"
write_slice_index "$S" zulu alpha
write_child_index "$S/alpha" 'Alpha abstract'
write_child_index "$S/zulu" 'Zulu abstract'
run_script "$S" >/dev/null
BODY=$(generated_body "$S")
FIRST=$(printf '%s\n' "$BODY" | head -n 1)
assert_contains "declared order wins over disk order" "$FIRST" "[zulu]"

# --- verbatim abstract copy ---------------------------------------------------
S="$TEST_TMPDIR/verbatim"
write_slice_index "$S" kid
# shellcheck disable=SC2016  # the backticks are literal fixture content, not an expansion
write_child_index "$S/kid" '"Keeps  spacing, a # mark, and `ticks` verbatim"'
run_script "$S" >/dev/null
BODY=$(generated_body "$S")
# shellcheck disable=SC2016  # asserting the literal backticks survived
assert_contains "abstract is mirrored verbatim" "$BODY" 'Keeps  spacing, a # mark, and `ticks` verbatim'

# --- zero-children slice ------------------------------------------------------
S="$TEST_TMPDIR/zero"
write_slice_index "$S"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "zero-children slice exits 0" 0 "$rc"
assert_contains "zero-children parity ok" "$OUT" "parity: ok (0 declared, 0 on disk)"
BODY=$(generated_body "$S")
assert_eq "zero-children body is the explicit placeholder" "(no child slices)" "$BODY"

# --- index-less leaf: abstract resolves via the reserved-name precedence ------
S="$TEST_TMPDIR/leaf"
write_slice_index "$S" explored planned
write_leaf_artifact "$S/explored" EXPLORE.md 'Explore-derived abstract'
write_leaf_artifact "$S/planned" PLAN.md 'Plan-derived abstract'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "index-less leaves regenerate cleanly" 0 "$rc"
BODY=$(generated_body "$S")
assert_contains "EXPLORE.md leaf links its sole artifact" "$BODY" "[explored](explored/EXPLORE.md) — Explore-derived abstract"
assert_contains "PLAN.md leaf links its sole artifact" "$BODY" "[planned](planned/PLAN.md) — Plan-derived abstract"
# INDEX.md outranks a co-present reserved artifact.
S="$TEST_TMPDIR/leaf-index-wins"
write_slice_index "$S" kid
write_child_index "$S/kid" 'Index-borne abstract'
write_leaf_artifact "$S/kid" EXPLORE.md 'Explore abstract that must lose'
run_script "$S" >/dev/null
BODY=$(generated_body "$S")
assert_contains "INDEX.md outranks EXPLORE.md" "$BODY" "[kid](kid/INDEX.md) — Index-borne abstract"

# --- multi-family leaf without an index is a parity error naming it -----------
S="$TEST_TMPDIR/multifam"
write_slice_index "$S" messy
write_leaf_artifact "$S/messy" EXPLORE.md 'Explore abstract'
write_leaf_artifact "$S/messy" RESEARCH.md 'Research abstract'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "multi-family leaf exits 1" 1 "$rc"
assert_contains "multi-family error names the child" "$OUT" "child 'messy'"
assert_contains "multi-family error names the families" "$OUT" "EXPLORE.md RESEARCH.md"
assert_contains "multi-family error demands an index" "$OUT" "requires an index"
BODY=$(generated_body "$S")
assert_eq "multi-family failure leaves the body untouched" "STALE BODY LINE" "$BODY"

# --- parity orphans, both directions ------------------------------------------
S="$TEST_TMPDIR/orphan-disk"
write_slice_index "$S" alpha
write_child_index "$S/alpha" 'Alpha abstract'
write_child_index "$S/undeclared" 'Undeclared abstract'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "on-disk orphan exits 1" 1 "$rc"
assert_contains "on-disk orphan is named" "$OUT" "on-disk child slice 'undeclared' is not in"
BODY=$(generated_body "$S")
assert_eq "on-disk orphan leaves the body untouched" "STALE BODY LINE" "$BODY"

# A duplicate declared name passes both membership walks (each copy finds the
# one directory), so it needs its own parity rejection.
S="$TEST_TMPDIR/dup-children"
write_slice_index "$S" alpha alpha
write_child_index "$S/alpha" 'Alpha abstract'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "duplicate declared child exits 1" 1 "$rc"
assert_contains "duplicate declared child is named" "$OUT" "child 'alpha' appears more than once"
BODY=$(generated_body "$S")
assert_eq "duplicate declared child leaves the body untouched" "STALE BODY LINE" "$BODY"

S="$TEST_TMPDIR/orphan-declared"
write_slice_index "$S" alpha ghost
write_child_index "$S/alpha" 'Alpha abstract'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "declared-but-missing orphan exits 1" 1 "$rc"
assert_contains "declared orphan is named" "$OUT" "declared child 'ghost' has no child-slice directory"

# A declared subdir that exists but holds no index artifact is still an orphan
# (the T5 predicate is content-derived, not name-derived).
S="$TEST_TMPDIR/orphan-empty-dir"
write_slice_index "$S" hollow
mkdir -p "$S/hollow"
printf '%s\n' 'not an index artifact' >"$S/hollow/notes.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "declared dir without index artifacts exits 1" 1 "$rc"
assert_contains "predicate failure is named" "$OUT" "declared child 'hollow'"

# --- interior noun-dirs are exempt from parity --------------------------------
S="$TEST_TMPDIR/interior"
write_slice_index "$S" alpha
write_child_index "$S/alpha" 'Alpha abstract'
mkdir -p "$S/design" "$S/baselines" "$S/scratch-x" "$S/resources"
printf '%s\n' 'design notes' >"$S/design/design-threads.md"
printf '%s\n' 'baseline blob' >"$S/baselines/run-1.txt"
printf '%s\n' 'scratch' >"$S/scratch-x/junk.md"
printf '%s\n' 'asset' >"$S/resources/diagram.svg"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "interior noun-dirs do not break parity" 0 "$rc"
assert_contains "interior noun-dirs: parity counts only the child slice" "$OUT" "parity: ok (1 declared, 1 on disk)"

# --- no INDEX.md: parity explicitly not-applicable ----------------------------
S="$TEST_TMPDIR/no-index"
mkdir -p "$S"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "slice without INDEX.md exits 0" 0 "$rc"
assert_contains "parity reported not-applicable, never silently passed" "$OUT" "parity: not-applicable"

# --- markers missing or duplicated exit 2 -------------------------------------
S="$TEST_TMPDIR/no-markers"
mkdir -p "$S"
{
  printf '%s\n' '---'
  printf '%s\n' 'slice: fixture'
  printf '%s\n' 'children:'
  printf '%s\n' '---'
  printf '%s\n' 'body with no markers'
} >"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "missing markers exit 2" 2 "$rc"
assert_contains "missing markers name the counts" "$OUT" "found 0 BEGIN, 0 END"

S="$TEST_TMPDIR/dup-markers"
write_slice_index "$S"
{
  printf '%s\n' "$BEGIN_MARKER"
  printf '%s\n' "$END_MARKER"
} >>"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "duplicated markers exit 2" 2 "$rc"
assert_contains "duplicated markers name the counts" "$OUT" "found 2 BEGIN, 2 END"

# --- size cap: exit 3, pre-existing body preserved, two-lever hint ------------
S="$TEST_TMPDIR/cap"
write_slice_index "$S" alpha
write_child_index "$S/alpha" 'A long enough abstract that the tiny cap below is exceeded'
rc=0
OUT=$(INDEX_REGEN_MAX_BYTES=64 bash "$SCRIPT" "$S" 2>&1) || rc=$?
assert_exit "size cap exits 3" 3 "$rc"
assert_contains "cap failure names the cap" "$OUT" "64-byte cap"
assert_contains "cap hint offers the decompose lever" "$OUT" "decompose this slice"
assert_contains "cap hint offers the abstract lever" "$OUT" "shorten child abstracts"
assert_contains "cap hint names the override env var" "$OUT" "INDEX_REGEN_MAX_BYTES"
BODY=$(generated_body "$S")
assert_eq "cap failure preserves the pre-existing body" "STALE BODY LINE" "$BODY"
# An invalid cap falls back to the default instead of silently disabling.
rc=0
OUT=$(INDEX_REGEN_MAX_BYTES=banana bash "$SCRIPT" "$S" 2>&1) || rc=$?
assert_exit "invalid cap value falls back to the default" 0 "$rc"
assert_contains "invalid cap value is called out" "$OUT" "not a positive integer"

# --- wrapped/multiline abstracts fail loudly ----------------------------------
S="$TEST_TMPDIR/wrapped-own"
mkdir -p "$S"
{
  printf '%s\n' '---'
  printf '%s\n' 'abstract: first half of a wrapped abstract'
  printf '%s\n' '  that continues on a second line'
  printf '%s\n' 'children:'
  printf '%s\n' '---'
  printf '%s\n' "$BEGIN_MARKER"
  printf '%s\n' "$END_MARKER"
} >"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "wrapped abstract in the slice index exits 2" 2 "$rc"
assert_contains "wrapped abstract is diagnosed" "$OUT" "ONE unwrapped line"

S="$TEST_TMPDIR/wrapped-child"
write_slice_index "$S" kid
mkdir -p "$S/kid"
{
  printf '%s\n' '---'
  printf '%s\n' 'abstract: >'
  printf '%s\n' '  a folded block scalar abstract'
  printf '%s\n' '---'
} >"$S/kid/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "block-scalar child abstract exits 2" 2 "$rc"
assert_contains "block scalar is diagnosed" "$OUT" "block scalar"

S="$TEST_TMPDIR/no-abstract"
write_slice_index "$S" kid
mkdir -p "$S/kid"
{
  printf '%s\n' '---'
  printf '%s\n' 'status: active'
  printf '%s\n' '---'
} >"$S/kid/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "child with no abstract exits 2" 2 "$rc"
assert_contains "missing child abstract is diagnosed" "$OUT" "no one-line abstract"

# --- underscore-emphasis abstracts fail loudly (formatter oscillation) --------
# The always-on formatter rewrites _emphasis_/__strong__ (MD049/MD050 --fix)
# inside the generated body but never inside the source frontmatter, so a
# mirrored underscore-emphasis abstract would oscillate between regen and
# format forever.
S="$TEST_TMPDIR/emphasis-child"
write_slice_index "$S" kid
write_child_index "$S/kid" '"An abstract with _emphasis_ in it"'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "underscore emphasis in a child abstract exits 2" 2 "$rc"
assert_contains "underscore emphasis is diagnosed with the formatter rationale" "$OUT" "formatter rewrites"

S="$TEST_TMPDIR/emphasis-strong"
write_slice_index "$S" kid
write_child_index "$S/kid" '"An abstract with __strong__ text"'
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "double-underscore strong in a child abstract exits 2" 2 "$rc"

S="$TEST_TMPDIR/emphasis-own"
mkdir -p "$S"
{
  printf '%s\n' '---'
  printf '%s\n' 'abstract: a slice abstract using _emphasis_ too'
  printf '%s\n' 'children:'
  printf '%s\n' '---'
  printf '%s\n' "$BEGIN_MARKER"
  printf '%s\n' "$END_MARKER"
} >"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "underscore emphasis in the slice's own abstract exits 2" 2 "$rc"

# Intraword underscores are not emphasis and must stay legal.
S="$TEST_TMPDIR/emphasis-snake"
write_slice_index "$S" kid
write_child_index "$S/kid" '"Keeps snake_case_names and https://example.com/a_b_page intact"'
rc=0
run_script "$S" >/dev/null || rc=$?
assert_exit "snake_case and underscored URLs stay legal" 0 "$rc"
BODY=$(generated_body "$S")
assert_contains "intraword underscores are mirrored verbatim" "$BODY" "snake_case_names and https://example.com/a_b_page"

# --- formatter-corruption regression (T3) -------------------------------------
# The always-on markdown formatter was shown to rewrite a wrapped continuation
# line starting with '+' into a '-' list marker. The generated body must keep
# each abstract on ONE line so no such continuation can ever exist for the
# formatter to corrupt.
S="$TEST_TMPDIR/plus-regression"
write_slice_index "$S" kid
write_child_index "$S/kid" '"Adds the new gate + keeps the old one running until the flip"'
rc=0
run_script "$S" >/dev/null || rc=$?
assert_exit "abstract containing ' + ' regenerates cleanly" 0 "$rc"
BODY=$(generated_body "$S")
assert_eq "generated body is exactly one line per child" 1 "$(printf '%s\n' "$BODY" | wc -l | tr -d '[:space:]')"
assert_contains "the + survives verbatim on the single line" "$BODY" "Adds the new gate + keeps the old one running until the flip"
FIRSTCHARS=$(printf '%s' "$BODY" | cut -c1-2)
assert_eq "the line is a child entry, not a bare continuation" "- " "$FIRSTCHARS"
# And an INPUT abstract already corrupted into a wrapped '+' continuation is
# rejected rather than re-mirrored.
S="$TEST_TMPDIR/plus-wrapped-input"
mkdir -p "$S"
{
  printf '%s\n' '---'
  printf '%s\n' 'abstract: a would-be one-liner'
  printf '%s\n' '  + a continuation the formatter would rewrite to a list'
  printf '%s\n' 'children:'
  printf '%s\n' '---'
  printf '%s\n' "$BEGIN_MARKER"
  printf '%s\n' "$END_MARKER"
} >"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "a '+'-leading wrapped continuation exits 2" 2 "$rc"
assert_contains "the '+' continuation is diagnosed as a wrap" "$OUT" "ONE unwrapped line"
# The already-corrupted shape: the formatter rewrote the '+' continuation into
# a '-' list marker at column 0. This exercises the list-item-after-abstract
# guard specifically (discriminating case: the indented-continuation tests
# above never reach it).
S="$TEST_TMPDIR/dash-wrapped-input"
mkdir -p "$S"
{
  printf '%s\n' '---'
  printf '%s\n' 'abstract: a would-be one-liner'
  printf '%s\n' '- the corrupted continuation the formatter produced'
  printf '%s\n' 'children:'
  printf '%s\n' '---'
  printf '%s\n' "$BEGIN_MARKER"
  printf '%s\n' "$END_MARKER"
} >"$S/INDEX.md"
rc=0
OUT=$(run_script "$S") || rc=$?
assert_exit "a column-0 '-' continuation after abstract exits 2" 2 "$rc"
assert_contains "the '-' continuation hits the list-item guard" "$OUT" "list item after abstract"

if [[ "$FAILED" -eq 0 ]]; then
  printf '\nAll %d checks passed.\n' "$CASE_NUM"
  exit 0
fi
printf '\n%d/%d checks failed.\n' "$FAILED" "$CASE_NUM" >&2
exit 1
