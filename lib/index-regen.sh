#!/usr/bin/env bash
# Regenerate the marker-fenced child listing of a work-folder slice's INDEX.md,
# and grade frontmatter-vs-disk child parity while doing it. This is the shared
# regen script the topic-docs v3 design threads resolve to (T1-T5 in
# docs/topics/work-folder-hierarchy/design/design-threads.md): frontmatter is
# the single home for child order and slice status, the generated body between
# the markers is the only span this script ever rewrites, and only the
# orchestrating session invokes it.
#
# SINGLE SOURCE OF TRUTH: lib/index-regen.sh at the marketplace repo root. The
# copies materialized into consuming plugins exist because installed plugins
# are cache-isolated and must be self-contained — never edit a copy. Edit the
# source and run scripts/sync-index-regen.sh; CI rejects drifted copies.
#
# Usage:
#   index-regen.sh <slice-dir>
#
# Behavior (normative spec: design-threads.md T1-T5):
#   * Parses <slice-dir>/INDEX.md frontmatter — `slice`, `abstract`, `status`
#     scalars and the ordered `children` list (T1 Sketch A). Parsing is
#     hand-rolled, quote-aware and comment-safe, following
#     lib/parse-concern-value.sh's precedent; only root-indent keys count.
#   * Every abstract is ONE unwrapped line (T3). A wrapped or block-scalar
#     abstract fails loudly: the repo's always-on markdown formatter was shown
#     to rewrite a wrapped continuation starting with `+` into a `-` list
#     marker, silently corrupting verbatim-copied text.
#   * Rewrites ONLY the body between the T2 markers (see BEGIN_MARKER /
#     END_MARKER below), listing children in declared order, one line per
#     child, linking each child's entry point and mirroring its abstract
#     verbatim. The rewrite emits LF line endings throughout: input lines are
#     read CR-stripped, so a CRLF INDEX.md is normalized to LF on regeneration. A child's abstract is its own INDEX.md frontmatter `abstract`;
#     an index-less leaf's abstract comes from its sole reserved artifact,
#     resolved by precedence INDEX.md > EXPLORE.md > RESEARCH.md > INTENT.md >
#     PLAN.md > PRD.md > SOURCES.md. Two or more reserved artifacts with no
#     INDEX.md is a multi-family leaf that REQUIRES an index — a parity error
#     naming the child.
#   * Parity, both directions (T5): the frontmatter `children` list is compared
#     against on-disk CHILD-SLICE directories. A subdirectory counts as a child
#     slice iff its root contains INDEX.md or any reserved UPPERCASE index
#     artifact; every other subdirectory (design/, baselines/, scratch/,
#     resources/, ...) is slice-interior under the interior-freedom clause and
#     exempt. A slice with no INDEX.md reports parity `not-applicable`
#     explicitly — a skipped check must never look passed.
#   * Size cap (T4): when the regenerated INDEX.md would exceed the cap
#     (INDEX_REGEN_MAX_BYTES, default 25600 bytes ≈ 25KB) the script halts
#     with exit 3, leaves any pre-existing generated body intact, and names the
#     two levers: decompose the slice, or shorten abstracts. Never silent
#     truncation.
#
# Exit codes (T2):
#   0  regenerated (or already current), parity ok — or parity not-applicable
#   1  parity mismatch (orphan in either direction, or a multi-family leaf
#      without an index)
#   2  ungradeable shape: usage error, missing/duplicated markers, unparsable
#      frontmatter, a wrapped/multiline abstract, or an unresolvable child
#      abstract
#   3  size cap exceeded (pre-existing body preserved)
set -uo pipefail

readonly BEGIN_MARKER='<!-- BEGIN GENERATED: slice index — regenerated by the shared lib script; edits inside are lost -->'
readonly END_MARKER='<!-- END GENERATED: slice index -->'
# Reserved UPPERCASE index artifacts, in abstract-resolution precedence order
# (T3). INDEX.md is handled separately (it always wins).
readonly RESERVED_ARTIFACTS="EXPLORE.md RESEARCH.md INTENT.md PLAN.md PRD.md SOURCES.md"
readonly DEFAULT_MAX_BYTES=25600

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  cat <<EOF
index-regen.sh — regenerate a slice INDEX.md's marker-fenced child listing.

Usage:
  index-regen.sh <slice-dir>

Reads <slice-dir>/INDEX.md, parses its YAML frontmatter (slice, abstract,
status, children), and rewrites ONLY the body between the markers

  $BEGIN_MARKER
  $END_MARKER

listing the declared children in order, one line per child, each linking the
child's entry point and mirroring its one-line abstract verbatim. Frontmatter
is never touched.

Abstract resolution per child: the child's own INDEX.md frontmatter
\`abstract\`; for an index-less leaf, the sole reserved artifact's header
abstract, by precedence INDEX.md > EXPLORE.md > RESEARCH.md > INTENT.md >
PLAN.md > PRD.md > SOURCES.md. Two or more reserved artifacts without INDEX.md
is a multi-family leaf that requires an index (parity error). Every abstract
must be ONE unwrapped line; wrapped or block-scalar abstracts fail loudly.

Parity, both directions: the \`children\` list vs on-disk child-slice
directories. A subdirectory is a child slice iff its root holds INDEX.md or a
reserved UPPERCASE index artifact (EXPLORE.md, RESEARCH.md, INTENT.md,
PLAN.md, PRD.md, SOURCES.md); all other subdirectories are slice-interior and
exempt. A slice with no INDEX.md reports "parity: not-applicable" explicitly
and exits 0 without regenerating.

Size cap: if the regenerated INDEX.md would exceed INDEX_REGEN_MAX_BYTES
(default $DEFAULT_MAX_BYTES bytes) the script exits 3, preserves the
pre-existing generated body, and suggests the two levers: decompose the slice,
or shorten abstracts.

Exit codes:
  0  success (regenerated / already current / parity not-applicable)
  1  parity mismatch or multi-family leaf without an index
  2  usage error, missing or duplicated markers, or unparsable shape
     (frontmatter, wrapped/multiline abstract, unresolvable child abstract)
  3  size cap exceeded (nothing written)
EOF
  exit 0
fi

slice_dir="${1:-}"
if [[ -z "$slice_dir" ]]; then
  echo "index-regen: usage: index-regen.sh <slice-dir>  (--help for details)" >&2
  exit 2
fi
if [[ ! -d "$slice_dir" ]]; then
  echo "index-regen: not a directory: $slice_dir" >&2
  exit 2
fi
slice_dir="${slice_dir%/}"
index_file="$slice_dir/INDEX.md"

if [[ ! -f "$index_file" ]]; then
  # T5: a skipped check must never look passed — say so, explicitly.
  echo "parity: not-applicable (no INDEX.md in $slice_dir; nothing to regenerate)"
  exit 0
fi

shape_error() {
  echo "SHAPE: $*" >&2
  exit 2
}

# Peel a matching surrounding quote pair, strip a comment (quote-aware), trim
# surrounding whitespace — same discipline as lib/parse-concern-value.sh: quote
# resolution first, so a `#` inside quotes is never mistaken for a comment.
strip_scalar() {
  local raw="$1" val
  raw="${raw//$'\r'/}"
  raw="${raw#"${raw%%[![:space:]]*}"}"
  case "$raw" in
  '"'*)
    val="${raw#\"}"
    val="${val%%\"*}"
    ;;
  "'"*)
    val="${raw#\'}"
    val="${val%%\'*}"
    ;;
  *)
    val="$raw"
    if [[ "$val" == '#'* ]]; then
      val=""
    else
      val="${val%%[[:space:]]#*}"
    fi
    val="${val%"${val##*[![:space:]]}"}"
    ;;
  esac
  printf '%s' "$val"
}

# Parse the YAML frontmatter block of <file> into globals:
#   FM_ABSTRACT   the one-line abstract (empty when the key is absent/empty)
#   FM_CHILDREN   ordered child names (array; empty when no children key)
#   FM_END_INDEX  0-based index of the closing `---` line in FILE_LINES
# The whole file is left in FILE_LINES (CR-stripped). Enforces the T3 one-line
# rule: any continuation after `abstract:` — including a formatter-rewritten
# `-`/`+` line — is a shape error. Only root-indent keys count (nested
# same-named keys never answer for root ones, per parse-concern-value.sh).
FM_ABSTRACT=""
FM_CHILDREN=()
FM_END_INDEX=-1
FILE_LINES=()

parse_frontmatter() {
  local file="$1" label="$2"
  local line raw content indent base_indent=-1 cur_key="" i=0 total
  FM_ABSTRACT=""
  FM_CHILDREN=()
  FM_END_INDEX=-1
  FILE_LINES=()
  while IFS= read -r line || [[ -n "$line" ]]; do
    FILE_LINES+=("${line%$'\r'}")
  done <"$file"
  total=${#FILE_LINES[@]}
  if ((total == 0)) || [[ "${FILE_LINES[0]}" != "---" ]]; then
    shape_error "$label: no frontmatter block (file must open with ---)"
  fi
  i=1
  while ((i < total)); do
    raw="${FILE_LINES[$i]}"
    if [[ "$raw" == "---" ]]; then
      FM_END_INDEX=$i
      break
    fi
    # Indent, then content past it.
    content="${raw#"${raw%%[![:space:]]*}"}"
    indent=$((${#raw} - ${#content}))
    if [[ -z "$content" ]]; then
      i=$((i + 1))
      continue
    fi
    if [[ "$content" == '#'* ]]; then
      i=$((i + 1))
      continue
    fi
    if [[ "$content" =~ ^([A-Za-z_][A-Za-z0-9_-]*)[[:space:]]*:(.*)$ ]]; then
      local key="${BASH_REMATCH[1]}" rest="${BASH_REMATCH[2]}"
      if ((base_indent < 0)); then
        base_indent=$indent
      fi
      if ((indent == base_indent)); then
        cur_key="$key"
        case "$key" in
        abstract)
          local rest_trimmed
          rest_trimmed="${rest#"${rest%%[![:space:]]*}"}"
          case "$rest_trimmed" in
          '|'* | '>'*)
            shape_error "$label: abstract is a block scalar; abstracts must be ONE unwrapped line"
            ;;
          *) ;;
          esac
          FM_ABSTRACT="$(strip_scalar "$rest")"
          # An underscore-delimited emphasis span would be mirrored into the
          # generated body, where the always-on markdown formatter rewrites
          # _emphasis_/__strong__ (MD049/MD050 --fix) — but it never touches
          # this frontmatter, so every regen would re-plant what every format
          # pass rewrites: a permanent oscillation that breaks the verbatim
          # mirror. Only true emphasis spans are rejected; intraword
          # underscores (snake_case, underscored URL segments) are not
          # emphasis and stay legal.
          if [[ "$FM_ABSTRACT" =~ (^|[^[:alnum:]_])__?[^_[:space:]]([^_]*[^_[:space:]])?__?($|[^[:alnum:]_]) ]]; then
            shape_error "$label: abstract carries _-delimited emphasis; the markdown formatter rewrites _emphasis_/__strong__ in the generated body but never in this header, so the mirror would oscillate. Restyle with *asterisks* or plain text."
          fi
          ;;
        children)
          local cval
          cval="$(strip_scalar "$rest")"
          if [[ -n "$cval" && "$cval" != "[]" ]]; then
            shape_error "$label: children must be a block list (one '- name' per line) or []"
          fi
          ;;
        *) ;;
        esac
      else
        # A nested key line. Directly after `abstract:` it means the abstract
        # wrapped (or grew a nested mapping) — forbidden either way.
        if [[ "$cur_key" == "abstract" ]]; then
          shape_error "$label: abstract continues past its line; abstracts must be ONE unwrapped line"
        fi
      fi
    elif [[ "$content" == '-' || "$content" == -[[:space:]]* ]]; then
      if [[ "$cur_key" == "abstract" ]]; then
        # The formatter-corruption class (T3): a wrapped continuation the
        # markdown formatter rewrote into a `-` list marker, or a raw wrap.
        shape_error "$label: list item after abstract; abstracts must be ONE unwrapped line"
      fi
      if [[ "$cur_key" == "children" ]]; then
        local item
        item="$(strip_scalar "${content#-}")"
        if [[ -z "$item" ]]; then
          shape_error "$label: empty entry in children list"
        fi
        FM_CHILDREN+=("$item")
      fi
      # A list item under any other key is that key's own business — ignored.
    else
      if [[ "$cur_key" == "abstract" ]]; then
        shape_error "$label: abstract wraps onto a continuation line; abstracts must be ONE unwrapped line"
      fi
      if ((base_indent >= 0 && indent > base_indent)); then
        : # nested value of some other key — slice-interior, ignored
      else
        shape_error "$label: unparsable frontmatter line: $content"
      fi
    fi
    i=$((i + 1))
  done
  if ((FM_END_INDEX < 0)); then
    shape_error "$label: frontmatter block never closes (no terminating ---)"
  fi
}

# Is <dir> a child slice under the T5 predicate? Root holds INDEX.md or any
# reserved UPPERCASE index artifact; everything else is slice-interior.
is_child_slice() {
  local dir="$1" a
  [[ -f "$dir/INDEX.md" ]] && return 0
  for a in $RESERVED_ARTIFACTS; do
    [[ -f "$dir/$a" ]] && return 0
  done
  return 1
}

# --- Parse the slice's own INDEX.md -----------------------------------------
parse_frontmatter "$index_file" "$index_file"
declared_children=(${FM_CHILDREN[@]+"${FM_CHILDREN[@]}"})
fm_end_index=$FM_END_INDEX
slice_lines=("${FILE_LINES[@]}")
slice_line_count=${#slice_lines[@]}

# --- Marker audit (T2): exactly one BEGIN, exactly one END, in order --------
begin_count=0
end_count=0
begin_index=-1
end_index=-1
i=$((fm_end_index + 1))
while ((i < slice_line_count)); do
  case "${slice_lines[$i]}" in
  "$BEGIN_MARKER")
    begin_count=$((begin_count + 1))
    begin_index=$i
    ;;
  "$END_MARKER")
    end_count=$((end_count + 1))
    end_index=$i
    ;;
  *) ;;
  esac
  i=$((i + 1))
done
if ((begin_count != 1 || end_count != 1)); then
  echo "SHAPE: $index_file must contain exactly one BEGIN and one END slice-index marker (found $begin_count BEGIN, $end_count END)." >&2
  echo "  BEGIN: $BEGIN_MARKER" >&2
  echo "  END:   $END_MARKER" >&2
  exit 2
fi
if ((end_index < begin_index)); then
  echo "SHAPE: $index_file has its END marker before its BEGIN marker." >&2
  exit 2
fi

# --- Parity, both directions (T5) -------------------------------------------
disk_children=()
for d in "$slice_dir"/*/; do
  [[ -d "$d" ]] || continue # unmatched glob leaves the pattern itself
  name="${d%/}"
  name="${name##*/}"
  # shellcheck disable=SC2310  # predicate by design; a non-zero return is the "not a child slice" answer
  if is_child_slice "$d"; then
    disk_children+=("$name")
  fi
done

parity_errors=0
# A duplicate declared name would pass both membership walks below (each copy
# finds the one directory, the directory finds a copy), so it is caught here:
# the children list is the parity baseline AND the curated order, and a name
# listed twice makes both ambiguous.
di=0
for name in ${declared_children[@]+"${declared_children[@]}"}; do
  dj=0
  for other in ${declared_children[@]+"${declared_children[@]}"}; do
    if ((dj < di)) && [[ "$other" == "$name" ]]; then
      echo "PARITY: child '$name' appears more than once in $index_file's children list." >&2
      parity_errors=$((parity_errors + 1))
      break
    fi
    dj=$((dj + 1))
  done
  di=$((di + 1))
done
for name in ${declared_children[@]+"${declared_children[@]}"}; do
  found=0
  for dname in ${disk_children[@]+"${disk_children[@]}"}; do
    [[ "$dname" == "$name" ]] && found=1
  done
  if ((found == 0)); then
    echo "PARITY: declared child '$name' has no child-slice directory in $slice_dir (missing dir, or its root holds no INDEX.md / reserved index artifact)." >&2
    parity_errors=$((parity_errors + 1))
  fi
done
for dname in ${disk_children[@]+"${disk_children[@]}"}; do
  found=0
  for name in ${declared_children[@]+"${declared_children[@]}"}; do
    [[ "$name" == "$dname" ]] && found=1
  done
  if ((found == 0)); then
    echo "PARITY: on-disk child slice '$dname' is not in $index_file's children list." >&2
    parity_errors=$((parity_errors + 1))
  fi
done
if ((parity_errors > 0)); then
  echo "parity: MISMATCH ($parity_errors orphan(s)); $index_file left untouched." >&2
  exit 1
fi

# --- Resolve each child's entry point and one-line abstract (T3) ------------
generated_lines=()
for name in ${declared_children[@]+"${declared_children[@]}"}; do
  child_dir="$slice_dir/$name"
  entry=""
  if [[ -f "$child_dir/INDEX.md" ]]; then
    entry="INDEX.md"
  else
    families=""
    family_count=0
    for a in $RESERVED_ARTIFACTS; do
      if [[ -f "$child_dir/$a" ]]; then
        families="$families $a"
        family_count=$((family_count + 1))
        [[ -n "$entry" ]] || entry="$a"
      fi
    done
    if ((family_count >= 2)); then
      echo "PARITY: child '$name' holds multiple artifact families (${families# }) and no INDEX.md — a multi-family leaf requires an index." >&2
      echo "parity: MISMATCH (multi-family leaf); $index_file left untouched." >&2
      exit 1
    fi
  fi
  parse_frontmatter "$child_dir/$entry" "$child_dir/$entry"
  if [[ -z "$FM_ABSTRACT" ]]; then
    shape_error "$child_dir/$entry: no one-line abstract in its header; every indexable artifact's header carries abstract: (T3)"
  fi
  generated_lines+=("- [$name]($name/$entry) — $FM_ABSTRACT")
done
if ((${#generated_lines[@]} == 0)); then
  generated_lines=("(no child slices)")
fi

# --- Assemble the regenerated file ------------------------------------------
new_content=""
i=0
while ((i <= begin_index)); do
  new_content+="${slice_lines[$i]}"$'\n'
  i=$((i + 1))
done
for line in "${generated_lines[@]}"; do
  new_content+="$line"$'\n'
done
i=$end_index
while ((i < slice_line_count)); do
  new_content+="${slice_lines[$i]}"$'\n'
  i=$((i + 1))
done

# --- Size cap (T4) -----------------------------------------------------------
max_bytes="${INDEX_REGEN_MAX_BYTES:-$DEFAULT_MAX_BYTES}"
if ! [[ "$max_bytes" =~ ^[1-9][0-9]*$ ]]; then
  echo "index-regen: INDEX_REGEN_MAX_BYTES='$max_bytes' is not a positive integer; using default $DEFAULT_MAX_BYTES." >&2
  max_bytes=$DEFAULT_MAX_BYTES
fi
new_bytes=$(printf '%s' "$new_content" | wc -c)
new_bytes=$((new_bytes)) # normalize wc's padded output
if ((new_bytes > max_bytes)); then
  echo "SIZE CAP: regenerated $index_file would be $new_bytes bytes, over the ${max_bytes}-byte cap; the pre-existing generated body is preserved untouched." >&2
  echo "  Two levers (the cap is abstract length x child count): decompose this slice into sub-slices, or shorten child abstracts." >&2
  echo "  To raise the cap deliberately, set INDEX_REGEN_MAX_BYTES." >&2
  exit 3
fi

# --- Write only on change ----------------------------------------------------
old_content=""
for line in "${slice_lines[@]}"; do
  old_content+="$line"$'\n'
done
if [[ "$new_content" == "$old_content" ]]; then
  echo "unchanged: $index_file (${#declared_children[@]} children)"
else
  printf '%s' "$new_content" >"$index_file"
  echo "regenerated: $index_file (${#declared_children[@]} children)"
fi
echo "parity: ok (${#declared_children[@]} declared, ${#disk_children[@]} on disk)"
exit 0
