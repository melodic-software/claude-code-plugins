# shellcheck shell=bash
# Helpers shared by the vendor-backed update.sh scripts, library only.
#
# The caller defines FRONTMATTER_FILE (the skill's SKILL.md) and TMPDIR_RUN (a
# scratch directory it removes on exit), and the functions main calls:
# print_help, check_prereqs, run_check and run_apply. main reads those globals
# and calls those functions when it runs, so source this file before or after
# defining them. Sourcing defines functions and runs nothing.
#
# Shared source: lib/vendor-update.sh at the marketplace repo root is the
# canonical source; the copies beside each update.sh are generated by
# scripts/sync-shared-copies.sh and registered in scripts/shared-copies.txt.
# Edit this file and rerun the script.

log() { printf '%s\n' "$*"; }
err() { printf 'ERROR: %s\n' "$*" >&2; }
section() { printf '\n== %s ==\n' "$*"; }

# Replace a nested metadata field in the SKILL.md frontmatter, anchored to the
# indented key under the metadata: block so a top-level key never matches.
# shellcheck disable=SC2154  # FRONTMATTER_FILE and TMPDIR_RUN are the caller's
replace_metadata_field() {
  local field="$1" value="$2" tmp="${TMPDIR_RUN}/skill.md.tmp"
  # Escape chars special on sed's replacement side (& \ and the | delimiter) so
  # an upstream version string with metacharacters can't mangle the file.
  local value_safe
  value_safe=$(printf '%s' "$value" | sed 's/[&|\\]/\\&/g')
  sed -E "s|^([[:space:]]+${field}:[[:space:]]+).*\$|\\1${value_safe}|" \
    "$FRONTMATTER_FILE" >"$tmp"
  mv "$tmp" "$FRONTMATTER_FILE"
}

# shellcheck disable=SC2154  # FRONTMATTER_FILE is the caller's
main() {
  local mode="${1:---check}"

  if [[ "$mode" == -h || "$mode" == --help ]]; then
    print_help
    exit 0
  fi

  if [[ ! -f "$FRONTMATTER_FILE" ]]; then
    err "SKILL.md not found at $FRONTMATTER_FILE — run from a plugin checkout"
    exit 2
  fi

  check_prereqs

  case "$mode" in
  --check)
    run_check
    ;;
  --apply)
    run_apply
    ;;
  *)
    err "unknown mode: $mode (expected --check, --apply, or --help)"
    exit 2
    ;;
  esac
}
